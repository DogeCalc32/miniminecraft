function addBlocks()
    for y = 1, worldHeight, 1 do
        local row = {}
        local world_depth = 3
        for x = 1, worldWidth, 1 do
            if y < 3 then -- top 2 layers are sky
                table.insert(row, nil)
            elseif y == worldHeight then
                table.insert(row, Block:new("bedrock", x, y))
            elseif y == world_depth then
                table.insert(row, Block:new("grass", x, y))
            else
                local randomBlockType = getRandomBlock()
                table.insert(row, Block:new(randomBlockType, x, y))
            end
        end
        table.insert(world, row)
    end
end

function getRandomBlock()
    local rnd = math.random(100)
    if rnd < 60 then
        return "dirt"
    end
    if rnd < 90 then
        return "stone"
    end
    return "bed"
end

local function canMove(tx, ty)
    if ty > #world or ty < 1 then
        return false
    end
    return world[ty][tx] == 0
end

local function canMove(tx, ty)
    for _, block in ipairs(world) do
        if block.x == tx then
            if block.id > 0 then
                return true
            else
                return false
            end
        end
        if block.y == ty then
            if block.id > 0 then
                return true
            else
                return false
