local function canMove(tx, ty)
    if ty > player.y then
        ty = ty + 1
    end
    return world[ty][tx] == 0
end

function tryMove(dx, dy)
    local newX = player.x + dx
    local newY = player.y + dy
    if world[newY][newX]==nil then
        return
    end
    if canMove(newX, newY) then
        player.x = newX
        player.y = newY
    end
end

