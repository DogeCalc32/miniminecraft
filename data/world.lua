local Block = require("data/block")
world = {}

worldWidth = 100
worldHeight = 100

function world:getSaveData()
    local data = {}

    for y = 1, #self do
        data[y] = {}
        for x = 1, #self[y] do
            data[y][x] = self[y][x]
        end
    end

    return data
end

